<?php

namespace Ignite\Auth\Mail;

use Ignite\Interfaces\Auth\Ip;
use Ignite\Interfaces\Users\User;
use Illuminate\Bus\Queueable;
use Illuminate\Contracts\Queue\ShouldQueue;
use Illuminate\Mail\Mailable;
use Illuminate\Mail\Mailables\Content;
use Illuminate\Mail\Mailables\Envelope;
use Illuminate\Queue\SerializesModels;

class LogginAttemptedWithUnauthorisedIpMail extends Mailable implements ShouldQueue
{
    use Queueable;
    use SerializesModels;

    /**
     * Create a new message instance.
     *
     * @param \Ignite\Interfaces\Users\User $user
     * @param \Ignite\Interfaces\Auth\Ip    $ip
     *
     * @return void
     */
    public function __construct(
        protected readonly User $user,
        protected readonly Ip $ip
    ) {
    }

    /**
     * Get the message envelope.
     *
     * @return \Illuminate\Mail\Mailables\Envelope
     */
    public function envelope(): Envelope
    {
        return new Envelope(
            subject: 'Ignite Global - Loggin Attempted With Unauthorised Ip',
        );
    }

    /**
     * Get the message content definition.
     *
     * @return \Illuminate\Mail\Mailables\Content
     */
    public function content(): Content
    {
        return new Content(
            markdown: 'emails.auth.unauthorised-ip',
        );
    }

    /**
     * Get the attachments for the message.
     *
     * @return array<int, \Illuminate\Mail\Mailables\Attachment>
     */
    public function attachments(): array
    {
        return [];
    }
}
